"""
Link Layer Network Function
===========================

This package provides the :py:class:`LinkLayer` application, which implements elementary entanglement generation procedure.

Interacting with the LinkLayer
------------------------------

LinkLayer is activated via :py:class:`PathActivateEvent` and deactivated via :py:class:`PathDeactivateEvent`.
Typically, these events are sent by a component of :py:class:`~mqns.network.fw.Forwarder`.

The activation is scoped for a quantum channel connected to a peer node that also runs the LinkLayer application.
Both LinkLayer applications must be activated at the same time, with one designated as the primary node
and the other designates the secondary node.
Moreover, there must be a classical channel with the same peer node, which must have the exactly same one-way latency.

The LinkLayer application works with the peer LinkLayer to continuously generate elementary entanglements,
on a set of memory qubits assigned to the quantum channel and optionally allocated to the path_id specified in the activation.
Upon successful generation, the elementary entanglement is delivered via :py:class:`QubitEntangledEvent`,
which is typically received by the forwarder.
When a delivered memory qubit is no longer needed, it must be returned to LinkLayer via :py:class:`QubitReleasedEvent`,
so that a new elementary entanglement can be generated using this qubit.

Entanglement Generation Steps
-----------------------------

1. Reservation Request and Acceptance
^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^

The reservation step determines which memory qubit is used for generating a specific entangled pair.

1. The primary node locates and locks a qubit for the generation,
   and then sends a reservation request (RESERVE_REQ) to the secondary node.
2. The secondary node locates and locks a qubit for the generation,
   and then sends a reservation response (RESERVE_RES) to the primary node.
   If no qubit is available at the moment, the secondary node must wait until
   a qubit becomes available before sending the response.
3. The reservation step completes when the primary node receives the reservation response.

Each reservation is identified by a **reservation key** generated by ``_AUTOID()``.
This is theoretically a UUID, but is implemented as a global sequential counters for log analysis convenience.
The qubit address is local information and not carried in the reservation messages.

The qubit locked for a reservation cannot be released until either
(1) the entanglement is delivered upon successful generation and then released,
(2) the reservation is aborted (see below).

2. Physical Attempts
^^^^^^^^^^^^^^^^^^^^

MQNS LinkLayer implements **skip-ahead sampling** technique.
It differs from many other simulators in that, LinkLayer does not simulate physical processes such as
photon emission and detection, but calculates the success probability of a *generation attempt* based on
properties of the photon sources, detectors, and quantum channels.
These **link architecture** models are implemented in :py:mod:`mqns.entity.qchannel` package.

In this step, the LinkLayer application computes how many attempts are needed until successful generation,
as well as when the successful attempt would start and finish.
It then schedules events for the next step.

3. Success Notification
^^^^^^^^^^^^^^^^^^^^^^^

The link architecture dictates when the success notification could be delivered to the primary and secondary nodes,
based on the heralding requirements of the modeled generation protocol (e.g. Barrett-Kok).

Alt. Aborting a Reservation
^^^^^^^^^^^^^^^^^^^^^^^^^^^

If a deactivation command is received while a reservation is present:

* If the successful attempt has already started or is starting in the same time slot,
  it is too late to abort this reservation, and it must proceed to success notification.
* Otherwise, the reservation is aborted.

To abort a reservation, the primary node releases its qubit and sends a RESERVE_ABORT message to the secondary node.
The secondary node releases its qubit upon receiving this message.

Internal Architecture
---------------------

:py:class:`~mqns.network.ll.entangle_pri.LLEntangleProcPri` implements the entanglement generation steps
on a specific channel as the primary node.
It uses :py:class:`~mqns.network.ll.entangle_pri.LLPathPri` data structure to keep track of activations,
in which :py:attr:`~mqns.network.ll.entangle_pri.LLPathPri.oreq_table` records all ongoing reservations
since RESERVE_REQ until success notification.

:py:class:`~mqns.network.ll.entangle_2nd.LLEntangleProc2nd` implements the entanglement generation steps
on a specific channel as the secondary node.
It uses :py:class:`~mqns.network.ll.entangle_2nd.LLPath2nd` data structure to keep track of activations,
in which :py:attr:`~mqns.network.ll.entangle_2nd.LLPath2nd.ireq_queue` records reservations that are
not yet accepted due to lack of qubits.

The :py:class:`LinkLayer` class is responsible for creating and destroying the above per-channel objects,
and dispatching messages and events to the correct channel.
"""

